export function interpolate(template: string, values: Record<string, string | number | undefined>) {
  return template.replace(/\{\{(\w+)\}\}/g, (_, key) => `${values[key] ?? ''}`);
}

export function getPlayersManagementCopy(locale: Locale) {
  return PLAYERS_MANAGEMENT_COPY[locale] || PLAYERS_MANAGEMENT_COPY.en;
}

export function getPlayersManagementAccountName(locale: Locale, accountType: AccountType) {
  return getPlayersManagementCopy(locale).accountNames[accountType];
}
